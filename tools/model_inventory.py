#!/usr/bin/env python3
"""Generate docs/MODEL_STRUCTURE.md from the .slx files themselves.

A .slx file is a zip package; its block diagram is plain XML.  This tool reads
the XML and reports, for each model, what blocks it contains, which subsystems
it defines, what it takes in and out, and which MATLAB functions are embedded
in it (the extracted copies live in src/model_code/).

    python tools/model_inventory.py          # rewrite docs/MODEL_STRUCTURE.md
    python tools/model_inventory.py --check  # fail if the file is out of date
"""
from __future__ import annotations

import argparse
import collections
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIMULINK = os.path.join(ROOT, "src", "simulink")
MODEL_CODE = os.path.join(ROOT, "src", "model_code")
TARGET = os.path.join(ROOT, "docs", "MODEL_STRUCTURE.md")

MODELS = [
    ("task1_simulation.slx", "task1", "Posture regulation to the first target (Task 1)"),
    ("task2_simulation.slx", "task2", "Waypoint navigation across the noisy-Vicon region (Task 2)"),
    ("task3_simulation.slx", "task3", "Circular tracking around the cube under 90 % Vicon loss (Task 3)"),
    ("task4_simulation.slx", "task4", "LiDAR-EKF localization without motion capture (Task 4)"),
    ("task4_simulation_analytic_jacobian.slx", "task4_analytic",
     "Task 4 variant with the analytical LiDAR ray-wall Jacobian — the model behind the reported Task 4 results"),
    ("online_robot_2024b.slx", "online", "Real-robot model: Vicon input, ROS wheel-speed output, online task manager"),
]


def read_model(path):
    blocks = []
    with zipfile.ZipFile(path) as z:
        for entry in sorted(z.namelist()):
            if entry.startswith("simulink/systems/") and entry.endswith(".xml"):
                xml = z.read(entry).decode("utf8", "ignore")
                for m in re.finditer(r'<Block BlockType="([^"]*)" Name="([^"]*)"', xml):
                    blocks.append((m.group(1), m.group(2)))
    return blocks


def functions_for(prefix):
    folder = os.path.join(MODEL_CODE, prefix)
    if not os.path.isdir(folder):
        return []
    out = []
    for fn in sorted(os.listdir(folder)):
        if not fn.endswith(".m"):
            continue
        body = open(os.path.join(folder, fn), encoding="utf-8").read()
        sig = re.search(r"^function\b(.*)$", body.split("\n", 1)[-1], re.M)
        head = re.search(r"^function[^\n]*", body, re.M)
        out.append((fn, head.group(0).strip() if head else "function"))
    return out


def render():
    lines = []
    add = lines.append
    add("# Model structure")
    add("")
    add("Generated by `tools/model_inventory.py` from the `.slx` files themselves — a")
    add("Simulink model is a zip package whose block diagram is XML, so this table is")
    add("read out of the model rather than typed by hand. Re-run the tool after any")
    add("model change; `--check` fails when this file is stale.")
    add("")
    add("The algorithm is not only in the block wiring: each model carries MATLAB")
    add("Function blocks whose source is embedded in the package. Their code is")
    add("extracted verbatim into `src/model_code/<model>/` by `tools/extract_model_code.py`,")
    add("so it can be read and diffed outside MATLAB.")
    add("")
    for filename, prefix, role in MODELS:
        path = os.path.join(SIMULINK, filename)
        blocks = read_model(path)
        types = collections.Counter(t for t, _ in blocks)
        subs = sorted(n for t, n in blocks if t == "SubSystem")
        ins = sorted(n for t, n in blocks if t == "Inport")
        outs = sorted(n for t, n in blocks if t == "Outport")
        funcs = functions_for(prefix)
        add(f"## `src/simulink/{filename}`")
        add("")
        add(f"*{role}*")
        add("")
        add(f"- blocks: **{sum(types.values())}** ({len(types)} types)")
        add("- block mix: " + ", ".join(f"`{t}` {n}" for t, n in types.most_common(10)))
        add(f"- subsystems ({len(subs)}): " + (", ".join(f"`{s.strip()}`" for s in subs) or "—"))
        add(f"- inports ({len(ins)}): " + (", ".join(f"`{s.strip()}`" for s in ins) or "—"))
        add(f"- outports ({len(outs)}): " + (", ".join(f"`{s.strip()}`" for s in outs) or "—"))
        if funcs:
            add(f"- embedded MATLAB functions ({len(funcs)}), extracted to `src/model_code/{prefix}/`:")
            for fn, sig in funcs:
                add(f"  - `{fn}` — {sig}")
        else:
            add("- embedded MATLAB functions: none extracted")
        add("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
        if current != text:
            print("docs/MODEL_STRUCTURE.md is out of date", file=sys.stderr)
            return 1
        print("docs/MODEL_STRUCTURE.md is up to date")
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {TARGET} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
